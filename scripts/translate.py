VOCAB = TITLE + MACHINE + CHARACTER + TEAM + GOODS + MISC + EXTRA
# 長字串優先，避免短詞先替換造成破壞
VOCAB_SORTED = sorted(VOCAB, key=lambda kv: -len(kv[0]))


def translate(text):
    if not text:
        return text
    out = text
    for ja, zh in VOCAB_SORTED:
        if ja in out:
            out = out.replace(ja, zh)
    # 中文與英數之間補空格，提升可讀性
    out = re.sub(r"(?<=[\u4e00-\u9fff])(?=[A-Za-z0-9])", " ", out)
    out = re.sub(r"(?<=[A-Za-z0-9])(?=[\u4e00-\u9fff])", " ", out)
    # 清整空白
    out = re.sub(r"[ 　]{2,}", " ", out).strip()
    return out


# ---------- 發售時期 ----------
def translate_release(r):
    if not r:
        return None
    s = r
    if "発売未定" in s:
        return "發售日未定"
    s = s.replace("発売予定", "預定發售").replace("発売中", "發售中").replace("発売", "發售")
    s = s.replace("再販", "再販").replace("予約", "預購")
    s = s.replace("上旬", "上旬").replace("中旬", "中旬").replace("下旬", "下旬")
    s = s.replace("年", " 年 ").replace("月", " 月 ")
    s = re.sub(r"[ 　]{2,}", " ", s).strip()
    return s


def translate_series_line(s):
    if not s:
        return None
    out = translate(s)
    out = out.replace("No.", "No.")
    return out


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "../products.json"
    data = json.load(open(path))

    # 商品描述為完整日文段落，詞彙表替換會產生中日夾雜的破碎句，
    # 故改讀人工逐句翻譯的譯稿（key = JAN）。
    import os
    desc_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "desc_zh.json")
    try:
        DESC_ZH = {k: v for k, v in json.load(open(desc_path)).items()
                   if not k.startswith("_")}
    except FileNotFoundError:
        DESC_ZH = {}
        sys.stderr.write("警告：找不到 desc_zh.json，描述將不翻譯\n")

    untranslated = collections.Counter()

    for p in data["products"]:
        p["nameZh"] = translate(p["name"])
        jan = p.get("jan")
        if jan and jan in DESC_ZH:
            p["descZh"] = DESC_ZH[jan]
        p["releaseZh"] = translate_release(p.get("release"))
        if p.get("seriesLine"):
            p["seriesLineZh"] = translate_series_line(p["seriesLine"])
        if p.get("machine"):
            p["machine"]["zh"] = translate(p["machine"]["ja"])

        # 統計殘留的日文（假名）以便補詞
        for m in re.findall(r"[ぁ-んァ-ヴ]{2,}", p["nameZh"]):
            untranslated[m] += 1

    # 系列與分類名稱
    for s in data["series"]:
        s["name"] = {"TV版": "TV版", "11": "11", "ZERO": "ZERO",
                     "SAGA": "SAGA", "SIN": "SIN",
                     "未標示": "未標示"}.get(s["name"], s["name"])

    # 機體篩選清單重算（用翻譯後名稱）
    mc = collections.Counter(p["machine"]["zh"] for p in data["products"] if p.get("machine"))
    data["machines"] = [{"name": k, "count": v} for k, v in mc.most_common()]

    data["meta"]["lang"] = "zh-Hant"
    data["meta"]["translationNote"] = (
        "商品名稱為機器輔助翻譯（詞彙表逐詞替換），角色與機體採台灣通行譯名；"
        "未收錄之專有名詞保留日文原文。點擊商品可查看日文原名與來源頁。")

    json.dump(data, open(path, "w"), ensure_ascii=False, indent=1)

    print(f"已翻譯 {len(data['products'])} 件")
    print(f"機體清單：{[(m['name'], m['count']) for m in data['machines'][:8]]}")
    if untranslated:
        print(f"\n殘留假名詞（前 30，可補進詞彙表）：")
        for k, v in untranslated.most_common(30):
            print(f"  {k:20} {v}")


if __name__ == "__main__":
    main()
